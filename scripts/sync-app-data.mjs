#!/usr/bin/env node
/**
 * Bring the app's Scripture data into the companion.
 *
 * Three things cross, all of them written for or vendored by the app and none
 * of them licensed third-party material:
 *
 *   - the King James text, one module per book, loaded on demand
 *   - the verse counts per chapter and the 66-book canon
 *   - the 40 life topics and the 344 passages they point at
 *
 * Each becomes an ES module (`export default …`) rather than a JSON file. The
 * companion's Content Security Policy says `connect-src 'none'`, which keeps
 * writing local by forbidding every fetch, and a JSON file would need one.
 * A module import is governed by `script-src 'self'` instead, so the text
 * arrives the same way the application does and the policy stays as it is.
 *
 * Every generated file is recorded in compat/SOURCE.json with two hashes: the
 * native bytes it was made from (`sourceSha256`, what the drift workflow
 * compares against native main) and the bytes written here (`sha256`, what
 * `npm run verify:app-compat` checks locally). A regenerated module that
 * differs is therefore visible, and so is a native change nobody re-ran this
 * for.
 *
 * Usage:
 *   NATIVE_REPO=../my-life-with-christ node scripts/sync-app-data.mjs
 */

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NATIVE = resolve(process.env.NATIVE_REPO || resolve(ROOT, '../my-life-with-christ'));
const GENERATOR = 'scripts/sync-app-data.mjs';

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
/** Deterministic: the same input bytes always produce the same module bytes. */
const asModule = (header, value) => `// ${header}\n// Generated by ${GENERATOR} from the app. Do not edit by hand.\nexport default ${JSON.stringify(value)};\n`;

async function main() {
  const nativeSha = execFileSync('git', ['-C', NATIVE, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const dirty = execFileSync(
    'git',
    ['-C', NATIVE, 'status', '--porcelain', '--', 'src/data/topics.json', 'src/data/kjv', 'scripts/lib/books.mjs'],
    { encoding: 'utf8' },
  ).trim();
  if (dirty) {
    throw new Error(`The app's data files have uncommitted changes; sync from a committed state.\n${dirty}`);
  }

  const files = [];
  const record = async (nativePath, companionPath, output, why) => {
    const source = await readFile(join(NATIVE, nativePath));
    await mkdir(dirname(join(ROOT, companionPath)), { recursive: true });
    await writeFile(join(ROOT, companionPath), output);
    files.push({ companionPath, nativePath, kind: 'generated', why, sourceSha256: sha256(source), sha256: sha256(output) });
  };

  // The canon, from the file the app's ingest treats as the authority.
  const { BOOKS } = await import(pathToFileURL(join(NATIVE, 'scripts/lib/books.mjs')).href);
  const books = BOOKS.map(({ id, name, testament, order }) => ({ id, name, testament, order }));
  if (books.length !== 66) throw new Error(`expected 66 books, found ${books.length}`);
  await record(
    'scripts/lib/books.mjs',
    'dist/kjv/books.js',
    asModule('The 66-book canon: ids, names, testament and order, so a reference reads here exactly as it does in the app.', books),
    'Canonical book ids, names, testament and order.',
  );

  const versification = JSON.parse(await readFile(join(NATIVE, 'src/data/kjv/versification.json'), 'utf8'));
  await record(
    'src/data/kjv/versification.json',
    'dist/kjv/versification.js',
    asModule('Verse counts per chapter, keyed by book id. Small enough to load with the application.', versification),
    'Verse counts per chapter; every reference is checked against these.',
  );

  let verses = 0;
  for (const book of books) {
    const raw = JSON.parse(await readFile(join(NATIVE, `src/data/kjv/${book.id}.json`), 'utf8'));
    if (raw.id !== book.id || !Array.isArray(raw.chapters)) throw new Error(`unexpected shape in ${book.id}.json`);
    verses += raw.chapters.reduce((n, chapter) => n + chapter.length, 0);
    await record(
      `src/data/kjv/${book.id}.json`,
      `dist/kjv/${book.id}.js`,
      asModule(`${raw.name}, King James Version. Public domain in the United States; see kjv/SOURCE.md for the United Kingdom. Loaded on demand.`, raw),
      `King James text of ${raw.name}, loaded on demand.`,
    );
  }
  if (verses !== 31102) throw new Error(`expected 31,102 verses across the canon, found ${verses}`);

  const topicsFile = JSON.parse(await readFile(join(NATIVE, 'src/data/topics.json'), 'utf8'));
  if (!Array.isArray(topicsFile.topics) || topicsFile.topics.length === 0) throw new Error('topics.json has no topics');
  await record(
    'src/data/topics.json',
    'dist/topics.js',
    asModule('My Life With Christ topics: life topics mapped to Scripture references, each with a line on why it belongs. Written for the app, not generated from any outline.', topicsFile.topics),
    'The life topics and the passages they point at, written for this project.',
  );

  const provenance = await readFile(join(NATIVE, 'src/data/kjv/SOURCE.md'), 'utf8');
  await record(
    'src/data/kjv/SOURCE.md',
    'dist/kjv/SOURCE.md',
    `<!-- Copied from the app's src/data/kjv/SOURCE.md by ${GENERATOR}. The companion serves the same text as ES modules under dist/kjv/. -->\n\n${provenance}`,
    'KJV provenance and the copyright note, kept beside the text it describes.',
  );

  const manifestPath = resolve(ROOT, 'compat/SOURCE.json');
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  manifest.files = [...manifest.files.filter((file) => file.kind !== 'generated'), ...files];
  manifest.dataSourceSha = nativeSha;
  manifest.dataSyncedOn = new Date().toISOString().slice(0, 10);
  const note = 'A "generated" file is an ES module made from a native data file by scripts/sync-app-data.mjs: sourceSha256 is the native bytes (what the drift workflow compares), sha256 is the module written here (what verify:app-compat checks). dataSourceSha is the native commit the data was last synced from.';
  if (!manifest.notes.includes(note)) manifest.notes.push(note);
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

  console.log(`Synced ${files.length} data files from ${NATIVE} at ${nativeSha.slice(0, 8)}: ${books.length} books, ${verses.toLocaleString()} verses, ${topicsFile.topics.length} topics.`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
